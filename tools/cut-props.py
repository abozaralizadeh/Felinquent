#!/usr/bin/env -S uv run --with pillow --with numpy --with scipy python
"""Cuts the props sheet (things on a magenta background) into transparent WebP files.

Usage: tools/cut-props.py <sheet.png> <out-dir> <ts-file> name1 ... nameN [--height 3]

Things are read in grid order (left to right, top to bottom). Each one is trimmed and saved with its
bottom edge as the base. Its height in pixels is --height times its size in PROP_HEIGHT (so it stays
sharp at the large size on a Retina screen). The width to height ratio of every drawing goes into
<ts-file>, because the core cuts broken things into pieces and needs their shape (rows of drawings
cut from other sheets are kept).

The background colour is taken out of the soft edges ("unmixed"), so a glass keeps a faint white
tint where the background showed through it instead of a pink one.
"""
import json
import re
import sys
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

args = sys.argv[1:]
height_k = 3.0
if "--height" in args:
    i = args.index("--height")
    height_k = float(args[i + 1])
    del args[i : i + 2]
sheet, out_dir, ts_file, names = Path(args[0]), Path(args[1]), Path(args[2]), args[3:]
out_dir.mkdir(parents=True, exist_ok=True)

# Sizes from the core, so the drawings and the physics agree.
mess_ts = (Path(__file__).parent.parent / "src/core/mess.ts").read_text()
heights = {k: float(v) for k, v in re.findall(r"(\w+): (\d+)", re.search(r"PROP_HEIGHT[^{]*\{([^}]*)\}", mess_ts).group(1))}

img = np.asarray(Image.open(sheet).convert("RGB")).astype(np.float32)
r, g, b = img[..., 0], img[..., 1], img[..., 2]
magenta = np.minimum(r, b) - g
bg_mask = magenta > 190
bg = np.array([np.median(r[bg_mask]), np.median(g[bg_mask]), np.median(b[bg_mask])], dtype=np.float32)
bg_m = float(min(bg[0], bg[2]) - bg[1])

# How much of each pixel is the thing: none on the background, all once it has no magenta in it.
alpha = np.clip((bg_m - magenta) / (bg_m - 20.0), 0.0, 1.0)
# Unmix the background out of the soft pixels: seen = a * thing + (1 - a) * background.
a3 = np.maximum(alpha, 1e-3)[..., None]
rgb = np.clip((img - (1.0 - a3) * bg) / a3, 0, 255)
rgb[alpha >= 0.999] = img[alpha >= 0.999]

mask = alpha > 0.5
blobs, n = ndimage.label(ndimage.binary_dilation(mask, iterations=18))
sizes = ndimage.sum(mask, blobs, index=range(1, n + 1))
keep = [i + 1 for i in np.argsort(sizes)[::-1][: len(names)]]
if len(keep) < len(names):
    sys.exit(f"found only {len(keep)} things, expected {len(names)}")

found = []
for lab in keep:
    ys, xs = np.where((blobs == lab) & (alpha > 0.03))
    found.append((lab, ys.min(), ys.max(), xs.min(), xs.max(), (ys.min() + ys.max()) / 2, (xs.min() + xs.max()) / 2))
found.sort(key=lambda t: t[5])
tall_med = float(np.median([t[2] - t[1] for t in found]))
rows: list[list[tuple]] = []
for t in found:
    if rows and t[5] - rows[-1][-1][5] < 0.5 * tall_med:
        rows[-1].append(t)
    else:
        rows.append([t])
ordered = [t for row in rows for t in sorted(row, key=lambda t: t[6])]

aspect = {}
for name, (lab, y0, y1, x0, x1, _, _) in zip(names, ordered):
    if name == "-":
        continue
    region = (blobs == lab)[y0 : y1 + 1, x0 : x1 + 1]
    a = alpha[y0 : y1 + 1, x0 : x1 + 1] * region
    c = rgb[y0 : y1 + 1, x0 : x1 + 1]
    im = Image.fromarray(np.dstack([c, a * 255.0]).astype(np.uint8), "RGBA")
    bbox = im.getchannel("A").point(lambda v: 255 if v > 6 else 0).getbbox()
    im = im.crop(bbox)
    target_h = round(heights[name] * height_k)
    w = max(1, round(im.width * target_h / im.height))
    im = im.resize((w, target_h), Image.LANCZOS)
    im.save(out_dir / f"{name}.webp", "WEBP", quality=92, method=6)
    aspect[name] = round(im.width / im.height, 3)
    print(f"{name}: {im.width}x{im.height}")

# Keep the rows of drawings cut from other sheets.
if ts_file.exists():
    old = re.search(r"\{(.*)\}", ts_file.read_text())
    kept = {k: float(v) for k, v in re.findall(r"(\w+): ([\d.]+)", old.group(1))} if old else {}
    aspect = {**kept, **aspect}
ts_file.write_text(
    "// Generated by tools/cut-props.py: width / height of each prop drawing. Do not edit.\n"
    f"export const PROP_ASPECT: Record<string, number> = {json.dumps(aspect, separators=(",", ":")).replace('\"', '').replace(',', ', ').replace(':', ': ')};\n"
)
print(f"wrote {ts_file}")
